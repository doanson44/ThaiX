namespace ThaiX.Client.Services.Games.FrontlineTowerDefense;

public sealed record FrontlineLevelMapDefinition(
    string Id,
    int LevelNumber,
    bool IsBonus,
    int GameFrame,
    IReadOnlyList<FrontlineGridPoint> StartPoints,
    IReadOnlyList<FrontlineGridPoint> EndPoints,
    IReadOnlyList<FrontlineGridPoint> WalkableCells,
    IReadOnlyList<FrontlineGridPoint> BlockedCells)
{
    public const int GridWidth = 25;
    public const int GridHeight = 25;
    public int ProgressIndex => IsBonus ? 15 + (LevelNumber - 1) * 2 : LevelNumber - 1;
    public const int BuildableWidth = 21;
    public const int BuildableHeight = 15;

    public bool IsBuildable(FrontlineGridPoint cell) =>
        cell.X >= 0 && cell.X < BuildableWidth
        && cell.Y >= 0 && cell.Y < BuildableHeight
        && !WalkableCells.Contains(cell)
        && !BlockedCells.Contains(cell);

    public FrontlineGridMap CreateGridMap()
    {
        var walkable = new bool[GridWidth, GridHeight];
        foreach (var cell in WalkableCells)
        {
            if (cell.X >= 0 && cell.X < GridWidth && cell.Y >= 0 && cell.Y < GridHeight)
                walkable[cell.X, cell.Y] = true;
        }

        return new FrontlineGridMap(walkable);
    }
}

